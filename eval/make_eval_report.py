"""M9 eval report: per-language numbers, honest weak spots, product-track notes -> docs/EVAL_REPORT.md.

Built only from measured files in eval/out/ and eval/ratings/ (via eval.make_report helpers). Missing data -> PENDING.
  python -m eval.make_eval_report
"""
from __future__ import annotations

import statistics

from eval.common import ROOT
from eval.make_report import LANGS, fmt, load_all, load_ratings

NAMES = {"en": "English", "ja": "Japanese", "hi": "Hindi", "bn": "Bengali", "kn": "Kannada"}
PRODUCT_TTS = {"en": "Kokoro (Apache-2.0)", "ja": "Kokoro (Apache-2.0; voices graded C+ or lower by its authors) or Qwen3-TTS",
               "hi": "Indic Parler-TTS (Apache-2.0)", "bn": "Indic Parler-TTS (Apache-2.0)", "kn": "Indic Parler-TTS (Apache-2.0)"}


def main():
    data = load_all()
    ratings = load_ratings()
    by = lambda kind: [d for d in data if d.get("kind") == kind]
    stt = [d for d in by("stt") if not d.get("synthetic")]
    lid = [d for d in by("lid") if not d.get("synthetic")]
    tts = next(iter(by("tts")), None)
    llm = by("llm")
    kb = next(iter(by("kb_retrieval")), None)
    sw = [d for d in by("switch") if not d.get("synthetic")]
    rt = by("redteam")
    out = ["# ShaOn Voice AI - evaluation report (M9)\n",
           "Generated by `python -m eval.make_eval_report` from measured files only. PENDING = not measured yet; "
           "nothing here is estimated. Raw tables: eval/results.md. Effects vs latency: design/perf.md.\n",
           "## Summary per language\n",
           "| | STT WER/CER (best engine) | LID top-1 | Claude: native script / rating | Retrieval hit@1 | TTS naturalness (best) | Verdict |",
           "|---|---|---|---|---|---|---|"]
    for lang in LANGS:
        best = None
        for d in stt:
            v = d["per_lang"].get(lang)
            if v:
                score = v.get("cer") if lang == "ja" else v.get("wer")
                if score is not None and (best is None or score < best[0]):
                    best = (score, d["engine"] + " " + str(d["options"].get("model") or d["options"].get("decoding") or ""))
        stt_s = f"{fmt(best[0], True)} ({best[1]})" if best else "PENDING"
        lid_s = fmt(lid[0]["raw_top1_per_lang"].get(lang), True) if lid else "PENDING"
        llm_s = "PENDING"
        for d in llm:
            v = d["per_lang"].get(lang)
            if v:
                sc = [s for (t, i), ss in ratings.items() if t == "llm" and f"/{lang}_" in i for s in ss]
                llm_s = f"{fmt(v['native_ok'], True)} / {statistics.mean(sc):.1f} ({len(sc)})" if sc else f"{fmt(v['native_ok'], True)} / rating PENDING"
        kb_s = fmt(kb["per_lang"].get(lang, {}).get("hit1"), True) if kb else "PENDING"
        tts_s = "PENDING"
        if tts:
            best_t = []
            for vid, v in tts["voices"].items():
                if v["lang"] == lang:
                    sc = [s for (t, i), ss in ratings.items() if t == "tts" and i.startswith(vid + "/") for s in ss]
                    if sc:
                        best_t.append((statistics.mean(sc), vid))
            measured_voices = [vid for vid, v in tts["voices"].items() if v["lang"] == lang]
            if best_t:
                m, vid = max(best_t)
                tts_s = f"{m:.1f} ({vid})"
            elif measured_voices:
                tts_s = f"speed measured ({', '.join(measured_voices)}); rating PENDING"
        measured = [x for x in (stt_s, lid_s, llm_s, tts_s) if "PENDING" not in x]
        verdict = "not decided (data PENDING)" if len(measured) < 4 else "decide in eval/decisions.md"
        out.append(f"| {NAMES[lang]} | {stt_s} | {lid_s} | {llm_s} | {kb_s} | {tts_s} | {verdict} |")
    out += ["", "## Language switching", ""]
    out.append("; ".join(f"{x['pair']} {'PASS' if x['pass'] else 'FAIL'}" for d in sw for x in d["pairs"]) or
               "PENDING: native recordings + `python -m eval.runners.run_switch` (synthetic en<->ja pipeline check passed, see results.md)")
    out += ["", "## Guardrails", ""]
    for d in rt:
        s = d["summary"]
        out.append(f"- {d['mode']}: {fmt(s['overall'], True)} of 50 attacks stopped "
                   f"(local-layer attacks {fmt(s['local_expected'], True)}, model-layer attacks {fmt(s['model_expected'], True)}).")
    if not any(d["mode"] == "claude" for d in rt):
        out.append("- With Claude (combined reply check): PENDING (needs the API key).")
    out += ["", "## Honest weak spots (known now)", "",
            "- No GPU numbers yet: every latency in this repo was measured on a 4-core VM without a GPU (CPU profile).",
            "- Whisper small (CPU profile) confuses Japanese homophones (支店 heard as 視点 in the E2E test). Large-v3 on GPU is expected to do better: measure.",
            "- Bengali and Kannada have no CPU speech voice: until Indic Parler / OmniVoice run on a GPU, replies in those languages are text only.",
            "- Kokoro's Hindi voice is a CPU fallback that no native speaker has rated yet.",
            "- Kokoro's own voice notes grade its Japanese voices C+ or lower: plan a native listening test before choosing it for Japanese.",
            "- Local guardrail rules cannot catch off-topic chat or most medical questions; they rely on the Claude reply check.",
            "- Language-ID thresholds in agent/engines.json are placeholders until run_lid.py measures them.",
            "", "## Product-track notes", "",
            "- OmniVoice weights are CC-BY-NC: demo only. Product voices must come from Apache-2.0 engines:"]
    out += [f"  - {NAMES[l]}: {PRODUCT_TTS[l]}" for l in LANGS]
    out += ["- STT: faster-whisper (MIT) for en/ja, IndicConformer (MIT) for hi/bn/kn; embeddings BGE-M3 (MIT); vector store Chroma (Apache-2.0).",
            "- Only text reaches the Anthropic API; audio stays on the machine. Hosting beyond a private demo needs a GPU host (paid): out of the $0 plan.", ""]
    p = ROOT / "docs" / "EVAL_REPORT.md"
    p.write_text("\n".join(out), encoding="utf-8")
    print(f"wrote {p}")


if __name__ == "__main__":
    main()
