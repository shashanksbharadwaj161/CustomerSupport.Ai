"""M9 eval report: per-language numbers, honest weak spots, product-track notes -> docs/EVAL_REPORT.md.

Built only from measured files in eval/out/ and eval/ratings/ (via eval.make_report helpers). Missing data -> PENDING.
  python -m eval.make_eval_report
"""
from __future__ import annotations

import statistics

from eval.common import ROOT
from eval.make_report import LANGS, fmt, load_all, load_ratings

NAMES = {"en": "English", "ja": "Japanese", "hi": "Hindi", "bn": "Bengali", "kn": "Kannada"}
PRODUCT_TTS = {"en": "Kokoro (Apache-2.0)", "ja": "Kokoro (Apache-2.0; voices graded C+ or lower by its authors) or Qwen3-TTS",
               "hi": "Indic Parler-TTS (Apache-2.0)", "bn": "Indic Parler-TTS (Apache-2.0)", "kn": "Indic Parler-TTS (Apache-2.0)"}


def main():
    data = load_all()
    ratings = load_ratings()
    by = lambda kind: [d for d in data if d.get("kind") == kind]
    stt = [d for d in by("stt") if not d.get("synthetic")]
    lid = [d for d in by("lid") if not d.get("synthetic")]
    tts = next(iter(by("tts")), None)
    llm = by("llm")
    kb = next(iter(by("kb_retrieval")), None)
    sw = [d for d in by("switch") if not d.get("synthetic")]
    rt = by("redteam")
    fl = [d for d in by("fleurs_stt") if d.get("status") == "measured"]
    flid = next(iter(by("fleurs_lid")), None)
    tcpu = next(iter(by("tts_cpu")), None)
    e2e = next(iter(by("indic_e2e")), None)
    LIC = {"faster-whisper": "MIT", "whisper-small": "MIT", "whisper-base": "MIT", "mms": "CC-BY-NC (eval/demo only)",
           "kokoro": "Apache-2.0", "mms-tts": "CC-BY-NC (DEMO ONLY)"}
    out = ["# ShaOn Voice AI - evaluation report (M9)\n",
           "Generated by `python -m eval.make_eval_report` from measured files only. PENDING = not measured yet; "
           "nothing here is estimated. Raw tables: eval/results.md. Effects vs latency: design/perf.md.\n",
           "**Read this first:** the real-audio numbers come from google/fleurs (CC-BY-4.0, Conneau et al. 2022): clean, read, "
           "Wikipedia-style speech, NOT phone calls, so error rates are optimistic for live calls. Everything was measured on a "
           "4-core CPU without a GPU; Whisper small/base are CPU stand-ins for the GPU engines (Whisper large-v3, IndicConformer). "
           "MMS models are CC-BY-NC (evaluation / demo only). Round-trip TTS CER is an intelligibility proxy, not naturalness.\n",
           "## Summary per language (CPU, real read speech)\n",
           "| | Best CPU STT on FLEURS (n) | LID accuracy (app path) | CPU TTS voice: RTF / round-trip CER proxy | Live-call E2E | License status | Native ratings |",
           "|---|---|---|---|---|---|---|"]
    for lang in LANGS:
        best = None
        for d in fl:
            v = d["per_lang"].get(lang)
            if v:
                m = v.get("cer") if lang == "ja" else v.get("wer")
                if m is not None and (best is None or m < best[0]):
                    best = (m, d["engine"], v["n"], "CER" if lang == "ja" else "WER")
        stt_s = f"{best[1]}: {best[3]} {fmt(best[0], True)} (n={best[2]})" if best else "PENDING"
        lid_s = fmt(flid["per_lang"][lang]["app_from_en"], True) + f" (n={flid['per_lang'][lang]['n']})" if flid else "PENDING"
        tts_s = "PENDING"
        if tcpu:
            vs = [(vid, v) for vid, v in tcpu["voices"].items() if v["lang"] == lang]
            if vs:
                tts_s = "; ".join(f"{vid}: RTF {v['rtf_median']} / {fmt(v.get('roundtrip_cer'), True)}" for vid, v in vs)
        if tts_s == "PENDING" and tts:
            vs = [vid for vid, v in tts["voices"].items() if v["lang"] == lang]
            if vs:
                tts_s = "; ".join(f"{vid}: RTF {tts['voices'][vid]['rtf_mean']}" for vid in vs)
        e2e_s = "PENDING"
        if e2e:
            turns = [t for c in e2e["cases"] for t in c["turns"] if t["want"] == lang]
            if turns:
                e2e_s = f"{sum(t['pass'] for t in turns)}/{len(turns)} turns pass"
        if lang in ("en", "ja") and e2e_s == "PENDING":
            e2e_s = "pass (earlier en/ja browser E2E, Kokoro audio)"
        lic = {"en": "Whisper MIT; Kokoro Apache-2.0", "ja": "Whisper MIT; Kokoro Apache-2.0",
               "hi": "Whisper MIT; MMS STT/TTS CC-BY-NC (demo); Kokoro-hi Apache-2.0", "bn": "Whisper MIT; MMS STT/TTS CC-BY-NC (demo only)",
               "kn": "Whisper MIT; MMS STT/TTS CC-BY-NC (demo only)"}[lang]
        out.append(f"| {NAMES[lang]} | {stt_s} | {lid_s} | {tts_s} | {e2e_s} | {lic} | PENDING (native speakers) |")
    if flid:
        b = flid.get("recommended") or {}
        out += ["", f"Language-ID threshold proposal from these clips: threshold {b.get('threshold')}, prev_bias {b.get('prev_bias')} "
                f"(stay {fmt(b.get('stay_acc'), True)}, switch {fmt(b.get('switch_acc'), True)}). CPU / read-speech estimate: re-measure on the demo PC."]
    out += ["", "Product-track engines (GPU) stay PENDING: IndicConformer (gated, needs HF token), Indic Parler-TTS, Whisper large-v3, OmniVoice (demo only).", ""]
    out += ["", "## Language switching", ""]
    out.append("; ".join(f"{x['pair']} {'PASS' if x['pass'] else 'FAIL'}" for d in sw for x in d["pairs"]) or
               "PENDING: native recordings + `python -m eval.runners.run_switch` (synthetic en<->ja pipeline check passed, see results.md)")
    out += ["", "## Guardrails", ""]
    for d in rt:
        s = d["summary"]
        out.append(f"- {d['mode']}: {fmt(s['overall'], True)} of 50 attacks stopped "
                   f"(local-layer attacks {fmt(s['local_expected'], True)}, model-layer attacks {fmt(s['model_expected'], True)}).")
    if not any(d["mode"] == "claude" for d in rt):
        out.append("- With Claude (combined reply check): PENDING (needs the API key).")
    out += ["", "## Honest weak spots (known now)", "",
            "- No GPU numbers yet: every latency in this repo was measured on a 4-core VM without a GPU (CPU profile).",
            "- Whisper small (CPU profile) confuses Japanese homophones (支店 heard as 視点 in the E2E test). Large-v3 on GPU is expected to do better: measure.",
            "- Bengali and Kannada speak on CPU only through the MMS voices: robotic, CC-BY-NC, pipeline-testing only. Product voices need Indic Parler on a GPU.",
            "- Kokoro's Hindi voice is a CPU fallback that no native speaker has rated yet.",
            "- Kokoro's own voice notes grade its Japanese voices C+ or lower: plan a native listening test before choosing it for Japanese.",
            "- Local guardrail rules cannot catch off-topic chat or most medical questions; they rely on the Claude reply check.",
            "- Language-ID thresholds in agent/engines.json are placeholders until run_lid.py measures them.",
            "", "## Product-track notes", "",
            "- OmniVoice weights are CC-BY-NC: demo only. Product voices must come from Apache-2.0 engines:"]
    out += [f"  - {NAMES[l]}: {PRODUCT_TTS[l]}" for l in LANGS]
    out += ["- STT: faster-whisper (MIT) for en/ja, IndicConformer (MIT) for hi/bn/kn; embeddings BGE-M3 (MIT); vector store Chroma (Apache-2.0).",
            "- Only text reaches the Anthropic API; audio stays on the machine. Hosting beyond a private demo needs a GPU host (paid): out of the $0 plan.", ""]
    p = ROOT / "docs" / "EVAL_REPORT.md"
    p.write_text("\n".join(out), encoding="utf-8")
    print(f"wrote {p}")


if __name__ == "__main__":
    main()
