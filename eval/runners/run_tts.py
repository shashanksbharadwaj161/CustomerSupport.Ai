"""M0 TTS bake-off: speed, time-to-first-audio, GPU memory, optional ASR round-trip, and a
manifest for native-speaker naturalness ratings (eval/tools/rater.html).

  python -m eval.runners.run_tts --engines kokoro indic-parler omnivoice
  python -m eval.runners.run_tts --voices omni_samelang_kn parler_kn_anu --roundtrip

Engines are loaded one at a time and unloaded after (memory). OmniVoice is DEMO ONLY
(CC-BY-NC weights); its reference clips are generated by Kokoro / Indic Parler here,
never recorded from a real person.
"""
from __future__ import annotations

import argparse
import gc
import json
import time

from agent import tts as tts_registry
from agent.audio import write_wav
from agent.tts.base import Voice
from eval.common import OUT, ROOT, GpuMem, load_lines, percentile, save

VOICES = ROOT / "voices" / "bakeoff_voices.json"
TTS_OUT = OUT / "tts"


def load_voices() -> tuple[dict, dict[str, Voice]]:
    cfg = json.loads(VOICES.read_text(encoding="utf-8"))
    voices = {v["id"]: Voice(id=v["id"], language=v["language"], engine=v["engine"],
                             display_name=v["display_name"], license=v["license"],
                             demo_only=v.get("demo_only", False), params=dict(v.get("params", {})))
              for v in cfg["voices"]}
    return cfg, voices


def ensure_ref_clips(cfg: dict, voices: dict[str, Voice], wanted: list[Voice]) -> None:
    """Generate model-made reference clips for OmniVoice clone voices that need them."""
    refs = {v.params["ref_from"] for v in wanted if v.params.get("ref_from")}
    (TTS_OUT / "refs").mkdir(parents=True, exist_ok=True)
    by_engine: dict[str, list[str]] = {}
    for rid in refs:
        if not (TTS_OUT / "refs" / f"{rid}.wav").exists():
            by_engine.setdefault(voices[rid].engine, []).append(rid)
    for eng_name, rids in by_engine.items():
        eng = tts_registry.create(eng_name)
        for rid in rids:
            rv = voices[rid]
            s = eng.synthesize(cfg["ref_text"][rv.language], rv)
            write_wav(str(TTS_OUT / "refs" / f"{rid}.wav"), s.audio, s.sample_rate)
            print(f"ref clip {rid} written (model-generated)")
        del eng
        _free()
    for v in wanted:
        rid = v.params.get("ref_from")
        if rid:
            v.params["ref_audio"] = str(TTS_OUT / "refs" / f"{rid}.wav")
            v.params["ref_text"] = cfg["ref_text"][voices[rid].language]


def _free():
    gc.collect()
    try:
        import torch

        if torch.cuda.is_available():
            torch.cuda.empty_cache()
    except Exception:
        pass


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--engines", nargs="*", help="limit to these engines")
    ap.add_argument("--voices", nargs="*", help="limit to these voice ids")
    ap.add_argument("--langs", nargs="*")
    ap.add_argument("--max-lines", type=int, default=10)
    ap.add_argument("--roundtrip", action="store_true",
                    help="transcribe outputs with the configured STT and report CER (intelligibility proxy)")
    a = ap.parse_args(argv)

    cfg, voices = load_voices()
    wanted = [v for v in voices.values()
              if (not a.engines or v.engine in a.engines) and (not a.voices or v.id in a.voices)
              and (not a.langs or v.language in a.langs)]
    if not wanted:
        print("no voices selected")
        return 1
    ensure_ref_clips(cfg, voices, wanted)
    lines = load_lines(include_mixed=False)

    results, manifest = {}, []
    for eng_name in sorted({v.engine for v in wanted}):
        eng = tts_registry.create(eng_name)
        with GpuMem() as mem:
            t0 = time.perf_counter()
            eng.ensure_loaded()
            load_s = time.perf_counter() - t0
            for v in [v for v in wanted if v.engine == eng_name]:
                vl = [l for l in lines if l["lang"] == v.language][: a.max_lines]
                eng.synthesize(vl[0]["text"], v)  # warm-up, excluded
                rows = []
                (TTS_OUT / v.id).mkdir(parents=True, exist_ok=True)
                for line in vl:
                    t = time.perf_counter()
                    s = eng.synthesize(line["text"], v)
                    gen_s = time.perf_counter() - t
                    dur = len(s.audio) / s.sample_rate
                    path = TTS_OUT / v.id / f"{line['id']}.wav"
                    write_wav(str(path), s.audio, s.sample_rate)
                    rows.append({"id": line["id"], "text": line["text"], "gen_ms": round(gen_s * 1000),
                                 # no engine streams yet: first audio = full generation time
                                 "first_audio_ms": round(gen_s * 1000),
                                 "audio_s": round(dur, 2), "rtf": round(gen_s / max(dur, 0.01), 3)})
                    manifest.append({"type": "tts", "item_id": f"{v.id}/{line['id']}", "lang": v.language,
                                     "voice": v.id, "demo_only": v.demo_only, "text": line["text"],
                                     "audio": f"tts/{v.id}/{line['id']}.wav"})
                    print(f"{v.id} {line['id']}: {gen_s*1000:6.0f} ms, {dur:4.1f} s audio")
                results[v.id] = {"engine": eng_name, "lang": v.language, "demo_only": v.demo_only,
                                 "license": v.license, "rows": rows,
                                 "first_audio_p50_ms": percentile([r["first_audio_ms"] for r in rows], 0.5),
                                 "first_audio_p90_ms": percentile([r["first_audio_ms"] for r in rows], 0.9),
                                 "rtf_mean": round(sum(r["rtf"] for r in rows) / len(rows), 3)}
        for v in [v for v in wanted if v.engine == eng_name]:
            results[v.id].update(load_s=round(load_s, 1), peak_gpu_mb=mem.peak_mb)
        del eng
        _free()

    if a.roundtrip:
        _roundtrip(results)

    old = json.loads((TTS_OUT / "manifest.json").read_text()) if (TTS_OUT / "manifest.json").exists() else []
    keep = [m for m in old if m["voice"] not in results]
    (TTS_OUT / "manifest.json").write_text(json.dumps(keep + manifest, ensure_ascii=False, indent=1))
    prev = (json.loads((OUT / "tts.json").read_text())["voices"] if (OUT / "tts.json").exists() else {})
    prev.update(results)
    p = save("tts", {"kind": "tts", "voices": prev})
    print(f"saved {p}")
    return 0


def _roundtrip(results: dict) -> None:
    from agent import stt as stt_registry
    from agent.audio import load_audio
    from eval.wer import aggregate, cer

    engines_cfg = json.loads((ROOT / "agent" / "engines.json").read_text())["stt"]
    cache = {}
    for vid, res in results.items():
        c = engines_cfg[res["lang"]]
        key = (c["engine"], json.dumps(c.get("options", {}), sort_keys=True))
        if key not in cache:
            cache[key] = stt_registry.create(c["engine"], **c.get("options", {}))
        stt = cache[key]
        scores = []
        for r in res["rows"]:
            hyp = stt.transcribe(load_audio(str(TTS_OUT / vid / f"{r['id']}.wav")), res["lang"]).text
            e, n = cer(r["text"], hyp)
            r["roundtrip_hyp"] = hyp
            scores.append({"cer_err": e, "cer_n": n})
        res["roundtrip_cer"] = aggregate(scores).get("cer")
        res["roundtrip_stt"] = c["engine"]


if __name__ == "__main__":
    raise SystemExit(main())
