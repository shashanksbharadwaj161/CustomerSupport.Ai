"""Build fake-microphone WAV files for the browser E2E test (Chrome --use-file-for-fake-audio-capture).
Speech is GENERATED by Kokoro (no real person's voice). Layout: 1.5 s silence, utterance, 58 s silence (Chrome loops the file; the long tail keeps one question per minute)."""
import pathlib
import sys

import numpy as np
import soundfile as sf

from agent.tts.base import Voice
from agent.tts.kokoro_tts import KokoroTTS

OUT = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else "tests/e2e/audio")
LINES = {
    "en_question": ("en", "af_heart", "What time does your branch open on Saturday?"),
    "ja_question": ("ja", "jf_alpha", "土曜日は支店が何時に開きますか。"),
}


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    tts = KokoroTTS()
    for name, (lang, voice, text) in LINES.items():
        s = tts.synthesize(text, Voice(id=name, language=lang, engine="kokoro", display_name=name, license="Apache-2.0", params={"voice": voice}))
        sr = s.sample_rate
        audio = np.concatenate([np.zeros(int(sr * 1.5)), s.audio, np.zeros(int(sr * 58))]).astype(np.float32)
        sf.write(OUT / f"{name}.wav", audio, sr, subtype="PCM_16")
        print(OUT / f"{name}.wav", round(len(audio) / sr, 1), "s")
    # one call that switches language: English question, pause, Japanese question
    import soundfile as sfr
    en, sr = sfr.read(OUT / "en_question.wav")
    ja, _ = sfr.read(OUT / "ja_question.wav")
    cut = lambda a: a[: len(a) - int(sr * 50)]  # drop most of the trailing silence
    sw = np.concatenate([cut(en), np.zeros(int(sr * 8)), ja]).astype(np.float32)
    sf.write(OUT / "switch_en_ja.wav", sw, sr, subtype="PCM_16")
    print(OUT / "switch_en_ja.wav", round(len(sw) / sr, 1), "s")


if __name__ == "__main__":
    main()
